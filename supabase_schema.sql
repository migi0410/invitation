-- 1. Bảng lưu danh sách khách mời & link thiệp (guests)
create table if not exists public.guests (
  id text primary key,
  name text not null,
  pose text not null default 'card1',
  sent boolean not null default false,
  created_at timestamptz not null default now()
);

-- 2. Bảng lưu Đôi lời thầm kín gửi Zunzun (wishes)
create table if not exists public.wishes (
  id bigint generated by default as identity primary key,
  guest_name text not null,
  message text not null,
  created_at timestamptz not null default now()
);

-- 3. Bảng lưu cấu hình hệ thống như Link Google Drive Nhận Ảnh (app_settings)
create table if not exists public.app_settings (
  key text primary key,
  value text not null default '',
  updated_at timestamptz not null default now()
);

insert into public.app_settings (key, value)
values ('photo_drive_url', '')
on conflict (key) do nothing;

-- 4. Bật Row Level Security (RLS) và cấp quyền cho Anon Key (Frontend Vercel)
alter table public.guests enable row level security;
alter table public.wishes enable row level security;
alter table public.app_settings enable row level security;

drop policy if exists "Allow public access to guests" on public.guests;
create policy "Allow public access to guests"
  on public.guests for all
  using (true)
  with check (true);

drop policy if exists "Allow public insert and select on wishes" on public.wishes;
create policy "Allow public insert and select on wishes"
  on public.wishes for all
  using (true)
  with check (true);

drop policy if exists "Allow public access to app_settings" on public.app_settings;
create policy "Allow public access to app_settings"
  on public.app_settings for all
  using (true)
  with check (true);
